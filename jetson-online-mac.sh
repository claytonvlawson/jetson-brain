#!/usr/bin/env bash
#
# jetson-online-mac.sh
#
# Share the Mac's WAN internet (en0 WiFi by default) with the NVIDIA Jetson
# Orin Nano over the USB-C link (192.168.55.0/24, Mac side en10) using macOS
# packet filter (pf) NAT plus IP forwarding.
#
# Subcommands:
#   start (default)   detect WAN + LAN, enable forwarding, load NAT anchor
#   stop              restore the default macOS pf ruleset, disable forwarding
#   status            report forwarding, pf state, and whether our NAT is loaded
#   install-daemon    copy this script + plist so sharing re-applies on boot
#   uninstall-daemon  remove the LaunchDaemon and its script copy
#
# Requires sudo. If not run as root the script re-executes itself under sudo.
# Idempotent and safe to re-run. No em dashes anywhere by design.

set -euo pipefail

# ----------------------------------------------------------------------------
# Constants
# ----------------------------------------------------------------------------
LAN_SUBNET="192.168.55.0/24"
LAN_MAC_IP="192.168.55.100"
LAN_FALLBACK_IF="en10"

ANCHOR_FILE="/etc/pf.anchors/jetson-nat"
BACKUP_DIR="/usr/local/var/jetson-online"
BACKUP_FILE="${BACKUP_DIR}/pf-original.backup"

DAEMON_LABEL="com.claytonlawson.jetson-online"
DAEMON_PLIST="/Library/LaunchDaemons/${DAEMON_LABEL}.plist"
INSTALLED_SCRIPT="/usr/local/bin/jetson-online-mac.sh"
LOG_FILE="/var/log/jetson-online.log"

# Resolve an absolute path to this script before any re-exec.
resolve_self() {
    local src="${BASH_SOURCE[0]}"
    local dir
    while [ -h "$src" ]; do
        dir="$(cd -P "$(dirname "$src")" >/dev/null 2>&1 && pwd)"
        src="$(readlink "$src")"
        [[ "$src" != /* ]] && src="$dir/$src"
    done
    dir="$(cd -P "$(dirname "$src")" >/dev/null 2>&1 && pwd)"
    printf '%s/%s\n' "$dir" "$(basename "$src")"
}
SELF_PATH="$(resolve_self)"

# ----------------------------------------------------------------------------
# Privilege check: re-exec under sudo if we are not root.
# ----------------------------------------------------------------------------
if [ "$(id -u)" -ne 0 ]; then
    echo "jetson-online-mac: elevating with sudo (you may be prompted for a password)."
    exec sudo "$SELF_PATH" "$@"
fi

# ----------------------------------------------------------------------------
# Detection helpers
# ----------------------------------------------------------------------------
detect_wan() {
    # Interface of the current default route (the Mac's internet uplink).
    local wan
    wan="$(route -n get default 2>/dev/null | awk '/interface:/{print $2; exit}')" || true
    printf '%s\n' "$wan"
}

detect_lan() {
    # Interface that currently holds the USB-C link IP; fall back to en10.
    local lan
    lan="$(ifconfig 2>/dev/null \
        | awk -v ip="$LAN_MAC_IP" '
            /^[a-z0-9]+:/ { iface=$1; sub(/:$/,"",iface) }
            $1=="inet" && $2==ip { print iface; exit }
        ')" || true
    if [ -z "${lan:-}" ]; then
        lan="$LAN_FALLBACK_IF"
    fi
    printf '%s\n' "$lan"
}

pf_is_enabled() {
    pfctl -s info 2>/dev/null | grep -q 'Status: Enabled'
}

nat_is_loaded() {
    pfctl -sn 2>/dev/null | grep -q "$LAN_SUBNET"
}

# ----------------------------------------------------------------------------
# Subcommand: start
# ----------------------------------------------------------------------------
cmd_start() {
    local WAN LAN
    WAN="$(detect_wan)"
    LAN="$(detect_lan)"

    if [ -z "${WAN:-}" ]; then
        echo "jetson-online-mac: could not determine the WAN interface (no default route)." >&2
        echo "jetson-online-mac: connect the Mac to the internet and retry." >&2
        exit 1
    fi

    # 1. Enable IPv4 forwarding.
    sysctl -w net.inet.ip.forwarding=1 >/dev/null

    # 2. Back up the current pf ruleset once (before we touch anything).
    if [ ! -f "$BACKUP_FILE" ]; then
        mkdir -p "$BACKUP_DIR"
        {
            echo "# jetson-online pf backup taken $(date)"
            echo "# ---- nat rules (pfctl -sn) ----"
            pfctl -sn 2>/dev/null || true
            echo "# ---- filter rules (pfctl -sr) ----"
            pfctl -sr 2>/dev/null || true
        } > "$BACKUP_FILE" || true
        echo "jetson-online-mac: saved original pf ruleset to ${BACKUP_FILE}."
    fi

    # 3. Write our NAT anchor as a self-contained pf ruleset.
    #    Translation (nat) rules must precede filter (pass) rules; pfctl
    #    enforces this ordering so the layout below is intentional.
    mkdir -p "$(dirname "$ANCHOR_FILE")"
    cat > "$ANCHOR_FILE" <<EOF
# jetson-nat: share the Mac WAN uplink with the Jetson USB-C subnet.
# Auto-generated by jetson-online-mac.sh. Do not edit by hand.
nat on ${WAN} from ${LAN_SUBNET} to any -> (${WAN})
pass all
EOF

    # 4. Load our ruleset and enable pf. pfctl may emit ALTQ or other
    #    warnings on macOS; those are non-fatal so we do not let them abort.
    local out rc
    set +e
    out="$(pfctl -ef "$ANCHOR_FILE" 2>&1)"
    rc=$?
    set -e
    # rc can be non-zero purely because pf was already enabled or because of
    # harmless warnings. Verify the real end state instead of trusting rc.
    if ! pf_is_enabled; then
        echo "jetson-online-mac: pf did not enable. pfctl said:" >&2
        printf '%s\n' "$out" >&2
        exit 1
    fi

    echo "jetson-online-mac: sharing ACTIVE."
    echo "  WAN uplink : ${WAN}"
    echo "  LAN link   : ${LAN} (${LAN_SUBNET})"
    echo "  forwarding : $(sysctl -n net.inet.ip.forwarding)"
    echo "  nat loaded : $(nat_is_loaded && echo yes || echo no)"
}

# ----------------------------------------------------------------------------
# Subcommand: stop
# ----------------------------------------------------------------------------
cmd_stop() {
    # Restore the stock macOS ruleset and turn forwarding back off.
    local out rc
    set +e
    out="$(pfctl -f /etc/pf.conf 2>&1)"
    rc=$?
    set -e
    if [ "$rc" -ne 0 ]; then
        echo "jetson-online-mac: note from pfctl while restoring /etc/pf.conf:" >&2
        printf '%s\n' "$out" >&2
    fi

    sysctl -w net.inet.ip.forwarding=0 >/dev/null

    echo "jetson-online-mac: sharing STOPPED."
    echo "  restored   : /etc/pf.conf"
    echo "  forwarding : $(sysctl -n net.inet.ip.forwarding)"
    echo "  nat loaded : $(nat_is_loaded && echo yes || echo no)"
}

# ----------------------------------------------------------------------------
# Subcommand: status
# ----------------------------------------------------------------------------
cmd_status() {
    local fwd pf_state nat_state
    fwd="$(sysctl -n net.inet.ip.forwarding 2>/dev/null || echo unknown)"
    if pf_is_enabled; then pf_state="enabled"; else pf_state="disabled"; fi
    if nat_is_loaded; then nat_state="loaded"; else nat_state="not loaded"; fi

    echo "jetson-online-mac status:"
    echo "  ip.forwarding : ${fwd}"
    echo "  pf            : ${pf_state}"
    echo "  jetson nat    : ${nat_state}"
    if [ "$nat_state" = "loaded" ]; then
        echo "  active nat rule(s):"
        pfctl -sn 2>/dev/null | grep "$LAN_SUBNET" | sed 's/^/    /' || true
    fi
}

# ----------------------------------------------------------------------------
# Subcommand: install-daemon
# ----------------------------------------------------------------------------
cmd_install_daemon() {
    # Copy this script to a stable system location the daemon can call.
    mkdir -p "$(dirname "$INSTALLED_SCRIPT")"
    if [ "$SELF_PATH" != "$INSTALLED_SCRIPT" ]; then
        cp "$SELF_PATH" "$INSTALLED_SCRIPT"
    fi
    chmod 755 "$INSTALLED_SCRIPT"
    chown root:wheel "$INSTALLED_SCRIPT"

    # Write the LaunchDaemon plist (kept byte-identical to the standalone
    # com.claytonlawson.jetson-online.plist deliverable).
    cat > "$DAEMON_PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>${DAEMON_LABEL}</string>
    <key>ProgramArguments</key>
    <array>
        <string>${INSTALLED_SCRIPT}</string>
        <string>start</string>
    </array>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <false/>
    <key>StandardOutPath</key>
    <string>${LOG_FILE}</string>
    <key>StandardErrorPath</key>
    <string>${LOG_FILE}</string>
</dict>
</plist>
EOF
    chown root:wheel "$DAEMON_PLIST"
    chmod 644 "$DAEMON_PLIST"

    # Reload cleanly: unload any prior copy first, then load.
    launchctl unload "$DAEMON_PLIST" 2>/dev/null || true
    launchctl load "$DAEMON_PLIST"

    echo "jetson-online-mac: LaunchDaemon installed."
    echo "  script : ${INSTALLED_SCRIPT}"
    echo "  plist  : ${DAEMON_PLIST}"
    echo "  log    : ${LOG_FILE}"
    echo "  sharing will re-apply automatically on boot."
}

# ----------------------------------------------------------------------------
# Subcommand: uninstall-daemon
# ----------------------------------------------------------------------------
cmd_uninstall_daemon() {
    if [ -f "$DAEMON_PLIST" ]; then
        launchctl unload "$DAEMON_PLIST" 2>/dev/null || true
        rm -f "$DAEMON_PLIST"
        echo "jetson-online-mac: removed ${DAEMON_PLIST}."
    else
        echo "jetson-online-mac: no LaunchDaemon plist at ${DAEMON_PLIST} (nothing to remove)."
    fi
    echo "jetson-online-mac: LaunchDaemon uninstalled. Existing sharing (if any) left untouched; run 'stop' to tear it down."
}

# ----------------------------------------------------------------------------
# Dispatch
# ----------------------------------------------------------------------------
main() {
    local cmd="${1:-start}"
    case "$cmd" in
        start)            cmd_start ;;
        stop)             cmd_stop ;;
        status)           cmd_status ;;
        install-daemon)   cmd_install_daemon ;;
        uninstall-daemon) cmd_uninstall_daemon ;;
        -h|--help|help)
            echo "Usage: $(basename "$0") {start|stop|status|install-daemon|uninstall-daemon}"
            ;;
        *)
            echo "jetson-online-mac: unknown subcommand '${cmd}'." >&2
            echo "Usage: $(basename "$0") {start|stop|status|install-daemon|uninstall-daemon}" >&2
            exit 2
            ;;
    esac
}

main "$@"
